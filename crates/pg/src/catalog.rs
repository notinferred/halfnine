//! What the app asks Postgres's catalog, and how the answers become core types.
//! Every name is cast to `text` so it decodes as a Rust `String` whatever Postgres's own type for it.

use std::collections::BTreeMap;

use sqlx::Row;
use sqlx::postgres::PgRow;
use tu_core::{ColumnInfo, Constraint, EnumType, ForeignKey, IncomingKey, Index, Relation, RelationKind, SchemaNode, Structure, TableRef};

pub(crate) const SERVER: &str = "SELECT current_setting('server_version'), current_database()::text, current_user::text, \
     ARRAY(SELECT datname::text FROM pg_database WHERE datallowconn AND NOT datistemplate ORDER BY datname)";

/// Every schema but those Postgres keeps for itself.
pub(crate) const SCHEMAS: &str =
    "SELECT nspname::text FROM pg_namespace WHERE nspname <> 'information_schema' AND nspname NOT LIKE 'pg\\_%' ORDER BY 1";

pub(crate) const RELATIONS: &str = "SELECT n.nspname::text, c.relname::text, c.relkind::text, \
     CASE WHEN c.reltuples < 0 THEN NULL ELSE c.reltuples::float8 END, \
     ARRAY(SELECT a.attname::text FROM pg_attribute a WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum) \
     FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace \
     WHERE c.relkind IN ('r', 'p', 'v', 'm', 'f', 'S') AND NOT c.relispartition \
     AND n.nspname <> 'information_schema' AND n.nspname NOT LIKE 'pg\\_%' \
     ORDER BY 1, 2";

/// Functions, leaving out those an extension installed (PostGIS alone brings thousands).
pub(crate) const FUNCTIONS: &str = "SELECT n.nspname::text, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' \
     FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace \
     WHERE n.nspname <> 'information_schema' AND n.nspname NOT LIKE 'pg\\_%' \
     AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.classid = 'pg_proc'::regclass AND d.objid = p.oid AND d.deptype = 'e') \
     ORDER BY 1, 2";

pub(crate) const ENUMS: &str = "SELECT n.nspname::text, t.typname::text, array_agg(e.enumlabel::text ORDER BY e.enumsortorder) \
     FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid JOIN pg_namespace n ON n.oid = t.typnamespace \
     GROUP BY 1, 2 ORDER BY 1, 2";

pub(crate) const RELATION: &str = "SELECT c.oid::int8, CASE WHEN c.reltuples < 0 THEN NULL ELSE c.reltuples::float8 END \
     FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = $1 AND c.relname = $2";

pub(crate) const COLUMNS: &str = "SELECT a.attname::text, format_type(a.atttypid, a.atttypmod), NOT a.attnotnull, \
     CASE a.attidentity WHEN 'a' THEN 'generated always as identity' WHEN 'd' THEN 'generated by default as identity' \
       ELSE CASE WHEN a.attgenerated = 's' THEN 'generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored' \
       ELSE pg_get_expr(d.adbin, d.adrelid) END END, \
     col_description(a.attrelid, a.attnum) \
     FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum \
     WHERE a.attrelid = $1::oid AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum";

pub(crate) const PRIMARY_KEY: &str = "SELECT ARRAY(SELECT a.attname::text FROM unnest(i.indkey::int2[]) WITH ORDINALITY k(attnum, ord) \
       JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = k.attnum ORDER BY k.ord) \
     FROM pg_index i WHERE i.indrelid = $1::oid AND i.indisprimary";

pub(crate) const INDEXES: &str = "SELECT c.relname::text, pg_get_indexdef(i.indexrelid), i.indisunique, i.indisprimary \
     FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid WHERE i.indrelid = $1::oid ORDER BY i.indisprimary DESC, 1";

pub(crate) const CONSTRAINTS: &str = "SELECT conname::text, pg_get_constraintdef(oid) FROM pg_constraint \
     WHERE conrelid = $1::oid AND contype IN ('c', 'u', 'x') ORDER BY 1";

pub(crate) const FOREIGN_KEYS: &str = "SELECT con.conname::text, tn.nspname::text, tc.relname::text, \
     ARRAY(SELECT a.attname::text FROM unnest(con.conkey) WITH ORDINALITY k(attnum, ord) \
       JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum ORDER BY k.ord), \
     ARRAY(SELECT a.attname::text FROM unnest(con.confkey) WITH ORDINALITY k(attnum, ord) \
       JOIN pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.attnum ORDER BY k.ord) \
     FROM pg_constraint con JOIN pg_class tc ON tc.oid = con.confrelid JOIN pg_namespace tn ON tn.oid = tc.relnamespace \
     WHERE con.contype = 'f' AND con.conrelid = $1::oid ORDER BY 1";

pub(crate) const REFERENCED_BY: &str = "SELECT con.conname::text, sn.nspname::text, sc.relname::text, \
     ARRAY(SELECT a.attname::text FROM unnest(con.conkey) WITH ORDINALITY k(attnum, ord) \
       JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum ORDER BY k.ord), \
     ARRAY(SELECT a.attname::text FROM unnest(con.confkey) WITH ORDINALITY k(attnum, ord) \
       JOIN pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.attnum ORDER BY k.ord) \
     FROM pg_constraint con JOIN pg_class sc ON sc.oid = con.conrelid JOIN pg_namespace sn ON sn.oid = sc.relnamespace \
     WHERE con.contype = 'f' AND con.confrelid = $1::oid ORDER BY 2, 3, 1";

/// The columns of a page, with each one's place in the primary key, if it has one.
pub(crate) const PAGE_COLUMNS: &str = "SELECT a.attname::text, format_type(a.atttypid, a.atttypmod), array_position(i.indkey::int2[], a.attnum) \
     FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace \
     JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped \
     LEFT JOIN pg_index i ON i.indrelid = c.oid AND i.indisprimary \
     WHERE n.nspname = $1 AND c.relname = $2 ORDER BY a.attnum";

pub(crate) fn schema_tree(schemas: &[PgRow], relations: &[PgRow], functions: &[PgRow], enums: &[PgRow]) -> Result<Vec<SchemaNode>, sqlx::Error> {
    let mut tree: BTreeMap<String, SchemaNode> = BTreeMap::new();
    for row in schemas {
        let name: String = row.try_get(0)?;
        tree.insert(
            name.clone(),
            SchemaNode {
                name,
                relations: Vec::new(),
                functions: Vec::new(),
                sequences: Vec::new(),
                enums: Vec::new(),
            },
        );
    }
    for row in relations {
        let Some(node) = tree.get_mut(&row.try_get::<String, _>(0)?) else {
            continue;
        };
        let name: String = row.try_get(1)?;
        let kind = match row.try_get::<String, _>(2)?.as_str() {
            "S" => {
                node.sequences.push(name);
                continue;
            }
            "p" => RelationKind::PartitionedTable,
            "v" => RelationKind::View,
            "m" => RelationKind::MaterializedView,
            "f" => RelationKind::ForeignTable,
            _ => RelationKind::Table,
        };
        node.relations.push(Relation {
            columns: row.try_get(4)?,
            name,
            kind,
            estimated_rows: row.try_get(3)?,
        });
    }
    for row in functions {
        if let Some(node) = tree.get_mut(&row.try_get::<String, _>(0)?) {
            node.functions.push(row.try_get(1)?);
        }
    }
    for row in enums {
        if let Some(node) = tree.get_mut(&row.try_get::<String, _>(0)?) {
            node.enums.push(EnumType {
                name: row.try_get(1)?,
                values: row.try_get(2)?,
            });
        }
    }
    Ok(tree.into_values().collect())
}

pub(crate) fn structure(
    estimated_rows: Option<f64>,
    columns: &[PgRow],
    key: Option<&PgRow>,
    indexes: &[PgRow],
    constraints: &[PgRow],
    outgoing: &[PgRow],
    incoming: &[PgRow],
) -> Result<Structure, sqlx::Error> {
    Ok(Structure {
        columns: columns
            .iter()
            .map(|r| {
                Ok(ColumnInfo {
                    name: r.try_get(0)?,
                    type_name: r.try_get(1)?,
                    nullable: r.try_get(2)?,
                    default: r.try_get(3)?,
                    comment: r.try_get(4)?,
                })
            })
            .collect::<Result<_, sqlx::Error>>()?,
        primary_key: key.map(|r| r.try_get(0)).transpose()?.unwrap_or_default(),
        indexes: indexes
            .iter()
            .map(|r| {
                Ok(Index {
                    name: r.try_get(0)?,
                    definition: r.try_get(1)?,
                    unique: r.try_get(2)?,
                    primary: r.try_get(3)?,
                })
            })
            .collect::<Result<_, sqlx::Error>>()?,
        constraints: constraints
            .iter()
            .map(|r| {
                Ok(Constraint {
                    name: r.try_get(0)?,
                    definition: r.try_get(1)?,
                })
            })
            .collect::<Result<_, sqlx::Error>>()?,
        foreign_keys: outgoing
            .iter()
            .map(|r| {
                Ok(ForeignKey {
                    name: r.try_get(0)?,
                    target: TableRef {
                        schema: r.try_get(1)?,
                        name: r.try_get(2)?,
                    },
                    columns: r.try_get(3)?,
                    target_columns: r.try_get(4)?,
                })
            })
            .collect::<Result<_, sqlx::Error>>()?,
        referenced_by: incoming
            .iter()
            .map(|r| {
                Ok(IncomingKey {
                    name: r.try_get(0)?,
                    source: TableRef {
                        schema: r.try_get(1)?,
                        name: r.try_get(2)?,
                    },
                    source_columns: r.try_get(3)?,
                    columns: r.try_get(4)?,
                })
            })
            .collect::<Result<_, sqlx::Error>>()?,
        estimated_rows,
    })
}
